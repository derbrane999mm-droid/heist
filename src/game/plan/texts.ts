const en: Record<string, string> = {};

export const PLAN_TEXTS = { de, en };

export interface Txt {
  k: string;
  p?: Record<string, any>;
}

export interface RenderCtx {
  lang: Lang;
  /** Display name of the crew member in a seat. */
  name(role: string): string;
}

export function hasText(k: string): boolean {
  return k in de;
}

export function eur(n: number): string {
  return Math.round(n).toLocaleString('de-DE') + ' €';
}

/** Look up a plain key (falls back to German, then to the key itself). */
export function pt(k: string, vars?: Record<string, string | number>, lang: Lang = 'de'): string {
  let s = (lang === 'en' ? en[k] : undefined) ?? de[k] ?? k;
  if (vars) for (const v in vars) s = s.split('{' + v + '}').join(String(vars[v]));
  return s;
}

/** Render a text from the logic with its parameters. */
export function tx(x: Txt | string | null | undefined, ctx: RenderCtx): string {
  if (x === null || x === undefined) return '';
  if (typeof x === 'string') return x;
  const vars: Record<string, string> = {};
  if (x.p)
    for (const key in x.p) {
      const v = x.p[key];
      if (v === null || v === undefined) vars[key] = '';
      else if (typeof v === 'string' || typeof v === 'number') vars[key] = String(v);
      else if ('r' in v) vars[key] = ctx.name(v.r);
      else if ('e' in v) vars[key] = eur(v.e);
      else vars[key] = tx(v as Txt, ctx);
    }
  return pt(x.k, vars, ctx.lang);
}

/** Every key used in a value tree (for the tests). */
export function keysIn(v: any, out: Set<string> = new Set()): Set<string> {
  if (Array.isArray(v)) for (const x of v) keysIn(x, out);
  else if (v && typeof v === 'object') {
    if (typeof v.k === 'string' && Object.keys(v).every((k) => k === 'k' || k === 'p')) out.add(v.k);
    for (const k in v) keysIn(v[k], out);
  }
  return out;
}
